-- Tranzacții programate și abonamente (funcționalitate în beta).
-- Doar adăugări: versiunea din producție nu folosește nimic de aici și funcționează la fel.

create table if not exists scheduled_entries (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  category_id integer references categories(id) on delete set null, -- categorie ștearsă → programarea stă pe loc
  amount double precision not null check (amount > 0),
  currency text not null default 'RON',
  frequency text not null default 'monthly' check (frequency in ('monthly', 'yearly')),
  day integer not null check (day between 1 and 31),
  month_of_year integer check (month_of_year between 1 and 12), -- doar la cele anuale
  start_month text not null,       -- YYYY-MM: prima lună în care se aplică
  end_month text,                  -- ultima lună (inclusiv); gol = fără sfârșit
  last_month text,                 -- ultima lună pentru care s-a creat intrarea
  is_subscription integer not null default 0,
  active integer not null default 1,
  created_at timestamptz not null default now()
);
create index if not exists idx_scheduled_entries_user on scheduled_entries (user_id);

alter table scheduled_entries enable row level security;
revoke all on scheduled_entries from anon, authenticated;
grant select, insert, update, delete on scheduled_entries to bp_app;
drop policy if exists own_rows on scheduled_entries;
create policy own_rows on scheduled_entries for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

-- Intrarea creată de o programare: legătura împiedică dublarea aceleiași luni.
-- Programarea ștearsă → intrările rămân, fără legătură.
alter table entries add column if not exists scheduled_id integer references scheduled_entries(id) on delete set null;
create unique index if not exists idx_entries_scheduled_month on entries (user_id, scheduled_id, month) where scheduled_id is not null;

grant usage, select on all sequences in schema public to bp_app;

