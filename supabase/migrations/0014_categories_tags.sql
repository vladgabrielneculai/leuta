-- Subcategorii, etichete și plăți împărțite pe mai multe categorii (funcționalitate în beta).
-- Doar adăugări: versiunea din producție nu folosește nimic de aici și funcționează la fel.
-- Numele categoriilor rămân unice în cont (idx_categories_unique_name nu se schimbă).

-- Subcategoria (ex. Mașină → Combustibil) arată spre categoria-părinte; părintele șters → devine categorie de sine.
alter table categories add column if not exists parent_id integer references categories(id) on delete set null;

-- Părțile unei plăți împărțite (un bon: 200 mâncare + 80 casă) au același identificator.
alter table entries add column if not exists split_group text;
create index if not exists idx_entries_split_group on entries (user_id, split_group) where split_group is not null;

create table if not exists tags (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  color text not null default '#2E5C8A',
  created_at timestamptz not null default now()
);
create unique index if not exists idx_tags_unique_name on tags (user_id, lower(trim(name)));

create table if not exists entry_tags (
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  entry_id integer not null references entries(id) on delete cascade,
  tag_id integer not null references tags(id) on delete cascade,
  primary key (entry_id, tag_id)
);
create index if not exists idx_entry_tags_tag on entry_tags (tag_id);

alter table tags enable row level security;
alter table entry_tags enable row level security;
revoke all on tags, entry_tags from anon, authenticated;
grant select, insert, update, delete on tags, entry_tags to bp_app;

drop policy if exists own_rows on tags;
create policy own_rows on tags for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

drop policy if exists own_rows on entry_tags;
create policy own_rows on entry_tags for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (
    user_id = nullif(current_setting('app.user_id', true), '')::integer
    and exists (select 1 from entries where entries.id = entry_id)
    and exists (select 1 from tags where tags.id = tag_id)
  );

-- Categoria-părinte trebuie să fie a aceluiași cont (ca în 0012_parent_ownership.sql). Nu prin regula RLS a
-- categoriilor: o regulă care citește din același tabel dă „infinite recursion detected in policy”. Regula
-- categoriilor rămâne neschimbată; verificarea o face un trigger, doar când parent_id e completat.
create or replace function categories_parent_same_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.parent_id is null then return new; end if;
  if new.parent_id = new.id then raise exception 'O categorie nu poate fi propria subcategorie.'; end if;
  if not exists (select 1 from categories c where c.id = new.parent_id and c.user_id = new.user_id and c.parent_id is null) then
    raise exception 'Categoria-părinte nu există.';
  end if;
  return new;
end $$;
revoke all on function categories_parent_same_user() from public;
drop trigger if exists trg_categories_parent on categories;
create trigger trg_categories_parent before insert or update of parent_id on categories
  for each row execute function categories_parent_same_user();

grant usage, select on all sequences in schema public to bp_app;

