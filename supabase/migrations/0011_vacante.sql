-- Vacanțe: cheltuielile de concediu, ținute separat de bugetul lunar (nu intră în entries / analytics).
--
-- Sumele se păstrează în moneda în care au fost plătite (ex. 48 EUR), nu în lei. Echivalentul în lei
-- e doar informativ și se calculează la afișare: cu cursul la care ai cumpărat valuta (trip_funds.rate_ron)
-- sau, dacă nu l-ai trecut, cu cursul BNR din fx_rates_currency.

create table trips (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  destination text not null default '',
  start_date text not null,                      -- 'YYYY-MM-DD'
  end_date text not null,
  currency text not null default 'EUR',          -- moneda locală a vacanței
  budget double precision not null default 0,    -- buget estimat, în moneda vacanței (0 = fără)
  notes text not null default '',
  created_at text not null default to_char(now(), 'YYYY-MM-DD"T"HH24:MI:SS')
);
create index on trips(user_id);

-- Banii pe care îi ai deja pentru vacanță, fiecare în moneda lui (ex. 600 EUR cash, 400 EUR pe card).
create table trip_funds (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  trip_id integer not null references trips(id) on delete cascade,
  label text not null default '',
  amount double precision not null,
  currency text not null,
  rate_ron double precision                      -- lei plătiți pe o unitate; null = curs BNR
);
create index on trip_funds(trip_id);

create table trip_expenses (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  trip_id integer not null references trips(id) on delete cascade,
  date text not null,                            -- 'YYYY-MM-DD'
  category text not null default 'altele',
  description text not null default '',
  amount double precision not null,
  currency text not null
);
create index on trip_expenses(trip_id);

-- Cursurile BNR pentru toate monedele publicate (fx_rates rămâne doar pentru EUR, folosit de buget).
-- `ron` = lei pentru o unitate (multiplicatorul BNR, ex. 100 HUF, e deja aplicat).
create table fx_rates_currency (
  date text not null,
  currency text not null,
  ron double precision not null,
  primary key (currency, date)
);

do $$
declare t text;
begin
  foreach t in array array['trips','trip_funds','trip_expenses','fx_rates_currency']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to bp_app', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to bp_app;

create policy own_rows on trips for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

-- Banii și cheltuielile se pot lega doar de o vacanță proprie (subinterogarea pe trips trece și ea prin RLS).
do $$
declare t text;
begin
  foreach t in array array['trip_funds','trip_expenses']
  loop
    execute format(
      'create policy own_rows on public.%I for all to bp_app
         using (user_id = nullif(current_setting(''app.user_id'', true), '''')::integer)
         with check (user_id = nullif(current_setting(''app.user_id'', true), '''')::integer
                     and exists (select 1 from trips where trips.id = trip_id))', t);
  end loop;
end $$;

create policy server_all on fx_rates_currency for all to bp_app using (true) with check (true);
