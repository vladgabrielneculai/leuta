-- Conturi (numerar, cont curent, economii, card) și transferuri între ele (funcționalitate în beta).
-- Doar adăugări: versiunea din producție nu folosește nimic de aici și funcționează la fel.
--
-- Soldul unui cont = soldul de pornire (la data de pornire) + veniturile − cheltuielile și economiile trecute
-- pe el de la acea dată + transferurile primite − cele trimise. Calculul e în aplicație (src/lib/accounts.ts).

create table if not exists accounts (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  kind text not null default 'current' check (kind in ('cash', 'current', 'savings', 'card', 'other')),
  currency text not null default 'RON',
  opening_balance double precision not null default 0,
  opening_date text not null,               -- YYYY-MM-DD: ziua la care soldul de pornire era cel trecut
  archived integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_accounts_user on accounts (user_id);

create table if not exists transfers (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  from_account_id integer not null references accounts(id) on delete cascade,
  to_account_id integer not null references accounts(id) on delete cascade,
  amount double precision not null check (amount > 0),   -- în moneda contului din care pleacă banii
  to_amount double precision check (to_amount > 0),      -- suma ajunsă, doar când monedele diferă (schimb valutar)
  date text not null,                                    -- YYYY-MM-DD
  note text not null default '',
  created_at timestamptz not null default now(),
  check (from_account_id <> to_account_id)
);
create index if not exists idx_transfers_user on transfers (user_id);

-- Contul pe care s-a făcut o intrare; cont șters → intrarea rămâne, fără cont.
alter table entries add column if not exists account_id integer references accounts(id) on delete set null;

alter table accounts enable row level security;
alter table transfers enable row level security;
revoke all on accounts, transfers from anon, authenticated;
grant select, insert, update, delete on accounts, transfers to bp_app;

drop policy if exists own_rows on accounts;
create policy own_rows on accounts for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

-- Ca în 0012_parent_ownership.sql: conturile legate trebuie să fie ale aceluiași utilizator.
drop policy if exists own_rows on transfers;
create policy own_rows on transfers for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (
    user_id = nullif(current_setting('app.user_id', true), '')::integer
    and exists (select 1 from accounts where accounts.id = from_account_id)
    and exists (select 1 from accounts where accounts.id = to_account_id)
  );

-- Regula intrărilor din 0012_parent_ownership.sql, plus contul. Producția nu trimite account_id, deci
-- condiția nouă e mereu adevărată pentru ea; rândurile existente nu sunt verificate din nou.
drop policy if exists own_rows on entries;
create policy own_rows on entries for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (
    user_id = nullif(current_setting('app.user_id', true), '')::integer
    and (category_id is null or exists (select 1 from categories where categories.id = category_id))
    and (goal_id is null or exists (select 1 from goals where goals.id = goal_id))
    and (investment_id is null or exists (select 1 from investments where investments.id = investment_id))
    and (account_id is null or exists (select 1 from accounts where accounts.id = account_id))
  );

grant usage, select on all sequences in schema public to bp_app;

