-- Importul extraselor de cont (funcționalitate în beta).
-- Doar adăugări: versiunea din producție nu folosește nimic de aici și funcționează la fel.

-- Amprenta tranzacției din extras: același extras încărcat de două ori nu dublează intrările.
alter table entries add column if not exists import_hash text;
create unique index if not exists idx_entries_import_hash on entries (user_id, import_hash) where import_hash is not null;

-- Reguli de categorisire învățate la import („kaufland” → Alimente), separate pe utilizator.
create table if not exists import_rules (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  pattern text not null,
  category_id integer not null references categories(id) on delete cascade,
  created_at timestamptz not null default now()
);
create unique index if not exists idx_import_rules_pattern on import_rules (user_id, pattern);
create index if not exists idx_import_rules_category on import_rules (category_id);

alter table import_rules enable row level security;
revoke all on import_rules from anon, authenticated;
grant select, insert, update, delete on import_rules to bp_app;
drop policy if exists own_rows on import_rules;
create policy own_rows on import_rules for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);
grant usage, select on all sequences in schema public to bp_app;

