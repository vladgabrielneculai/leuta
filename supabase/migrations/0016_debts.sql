-- Carduri de credit și descoperit de cont (funcționalitate în beta): datorii fără grafic fix de rambursare,
-- spre deosebire de credite (loans). Cumpărăturile în rate (BNPL) nu au tabel: sunt programări cu lună de
-- sfârșit în scheduled_entries. Doar adăugări: producția nu folosește nimic de aici.

create table if not exists debts (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  kind text not null default 'card' check (kind in ('card', 'overdraft')),
  credit_limit double precision not null default 0 check (credit_limit >= 0),
  balance double precision not null default 0 check (balance >= 0),   -- cât datorezi acum, lei
  balance_date text,                                                  -- YYYY-MM-DD: ziua soldului de mai sus
  rate double precision not null default 0 check (rate >= 0),         -- dobânda anuală, %
  min_payment_pct double precision not null default 5 check (min_payment_pct >= 0 and min_payment_pct <= 100),
  min_payment_amount double precision not null default 0 check (min_payment_amount >= 0), -- minimul în lei, oricât de mic e soldul
  due_day integer check (due_day between 1 and 31),                    -- ziua scadenței plății minime
  active integer not null default 1,
  created_at timestamptz not null default now()
);
create index if not exists idx_debts_user on debts (user_id);

alter table debts enable row level security;
revoke all on debts from anon, authenticated;
grant select, insert, update, delete on debts to bp_app;
drop policy if exists own_rows on debts;
create policy own_rows on debts for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

grant usage, select on all sequences in schema public to bp_app;

-- Revenire: drop table debts;
