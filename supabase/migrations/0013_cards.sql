-- Cardurile cu care plătești (funcționalitate în beta): o listă proprie, aleasă la adăugarea unei cheltuieli.
-- Doar adăugări: versiunea din producție nu folosește nimic de aici și funcționează la fel
-- (coloana nouă din entries e opțională, iar regula RLS acceptă în continuare orice intrare fără card).

create table if not exists cards (
  id integer generated by default as identity primary key,
  user_id integer not null default nullif(current_setting('app.user_id', true), '')::integer
          references users(id) on delete cascade,
  name text not null,
  kind text not null default 'bank' check (kind in ('bank', 'meal')), -- card bancar sau card de tichete de masă
  color text not null default '#2E5C8A',
  created_at timestamptz not null default now()
);
create index if not exists idx_cards_user on cards (user_id);
create unique index if not exists idx_cards_unique_name on cards (user_id, lower(trim(name)));

alter table cards enable row level security;
revoke all on cards from anon, authenticated;
grant select, insert, update, delete on cards to bp_app;
drop policy if exists own_rows on cards;
create policy own_rows on cards for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (user_id = nullif(current_setting('app.user_id', true), '')::integer);

-- Cardul cu care s-a plătit o intrare. Card șters → intrarea rămâne, fără card.
alter table entries add column if not exists card_id integer references cards(id) on delete set null;
create index if not exists idx_entries_card on entries (card_id) where card_id is not null;

-- Ca la categorii (0012_parent_ownership.sql): cardul unei intrări trebuie să fie al aceluiași cont.
drop policy if exists own_rows on entries;
create policy own_rows on entries for all to bp_app
  using (user_id = nullif(current_setting('app.user_id', true), '')::integer)
  with check (
    user_id = nullif(current_setting('app.user_id', true), '')::integer
    and (category_id is null or exists (select 1 from categories where categories.id = category_id))
    and (goal_id is null or exists (select 1 from goals where goals.id = goal_id))
    and (investment_id is null or exists (select 1 from investments where investments.id = investment_id))
    and (card_id is null or exists (select 1 from cards where cards.id = card_id))
  );

grant usage, select on all sequences in schema public to bp_app;

